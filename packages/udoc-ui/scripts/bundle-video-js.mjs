// Bundle Video.js into udoc-ui's dist. `dist/app/video-js.js`, tsc's output
// of src/app/video-js.ts, is rebuilt in place with every Video.js module it
// loads: each of its dynamic imports a chunk of its own in dist/app/video-js/,
// which it names relatively. So a host resolves no `@videojs/*` import and
// installs none of it — not even a host without a bundler, whose import map
// names udoc's packages alone. Run by `npm run build`, after tsc; `npm run dev`
// leaves tsc's output as it is.
//
// What it bundles is other people's software, so it writes their notices
// beside it: dist/THIRD-PARTY-NOTICES.md, each package that went in — as the
// bundle's metafile lists them — with its version, its license and its license
// text, one copy of a text the packages share.
import { build } from "esbuild";
import { readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const dist = join(here, "../dist");
const app = join(dist, "app");

// The chunks of an earlier build, which the new ones replace.
rmSync(join(app, "video-js"), { recursive: true, force: true });

const result = await build({
    entryPoints: [join(app, "video-js.js")],
    bundle: true,
    splitting: true,
    format: "esm",
    platform: "browser",
    target: "es2022",
    minify: true,
    outdir: app,
    entryNames: "[name]",
    chunkNames: "video-js/[name]-[hash]",
    allowOverwrite: true,
    metafile: true,
    logLevel: "warning",
});
// tsc's map is of the source this replaced.
rmSync(join(app, "video-js.js.map"), { force: true });

const chunks = readdirSync(join(app, "video-js"));
const bytes = chunks.reduce((sum, chunk) => sum + readFileSync(join(app, "video-js", chunk)).length, 0);
console.log(`[bundle-video-js] dist/app/video-js.js: ${chunks.length} chunks, ${Math.round(bytes / 1024)} KB`);

/** A package's repository as a URL: a `git+https://host/repo.git` one as its page, and npm's `owner/repo` and `github:owner/repo` shorthands as GitHub's. */
function sourceUrl(repository) {
    const shorthand = /^(?:github:)?([\w.-]+\/[\w.-]+)$/.exec(repository);
    if (shorthand) return `https://github.com/${shorthand[1]}`;
    return repository.replace(/^git\+/, "").replace(/\.git$/, "");
}

/** Each package the bundle took a file from, by its directory. */
const packages = new Map();
for (const input of Object.keys(result.metafile.inputs)) {
    const match = /^(.*node_modules\/(?:@[^/]+\/)?[^/]+)\//.exec(input);
    if (!match) continue;
    const directory = resolve(match[1]);
    if (packages.has(directory)) continue;
    const manifest = JSON.parse(readFileSync(join(directory, "package.json"), "utf8"));
    const texts = readdirSync(directory)
        .filter((file) => /^(licen[cs]e|notice|copying)/i.test(file))
        .sort()
        .map((file) => readFileSync(join(directory, file), "utf8").trim());
    if (texts.length === 0) throw new Error(`[bundle-video-js] ${manifest.name} ships no license text`);
    const repository = typeof manifest.repository === "string" ? manifest.repository : manifest.repository?.url;
    packages.set(directory, {
        name: manifest.name,
        version: manifest.version,
        license: manifest.license,
        source: sourceUrl(repository ?? manifest.homepage ?? `https://www.npmjs.com/package/${manifest.name}`),
        text: texts.join("\n\n"),
    });
}

// The packages that share a license text, word for word, under one copy of it.
const byText = new Map();
for (const pkg of [...packages.values()].sort((a, b) => a.name.localeCompare(b.name))) {
    byText.set(pkg.text, [...(byText.get(pkg.text) ?? []), pkg]);
}

const sections = [...byText].map(([text, sharing]) => {
    const list = sharing.map((pkg) => `- ${pkg.name} ${pkg.version} (${pkg.license}) — ${pkg.source}`).join("\n");
    return `${list}\n\n\`\`\`text\n${text}\n\`\`\``;
});
const notices = `# Third-party notices

The media document of \`@docmentis/udoc-ui\` plays video and audio on Video.js,
which this package bundles in \`dist/app/video-js.js\` and the chunks it loads
from \`dist/app/video-js/\`. That code is the software below, each package under
its own license, reproduced after the packages it covers. Generated by
\`scripts/bundle-video-js.mjs\` from what the bundle holds.

${sections.join("\n\n")}
`;
writeFileSync(join(dist, "THIRD-PARTY-NOTICES.md"), notices);
console.log(`[bundle-video-js] dist/THIRD-PARTY-NOTICES.md: ${packages.size} packages, ${byText.size} license texts`);
