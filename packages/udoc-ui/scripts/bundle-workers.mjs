// Bundle a local collaboration service's worker whole — the engine's glue
// included — and rewrite the module it starts from
// (`dist/worker/local-collaboration-worker-source.js`) to start it from a blob.
// Run by `npm run build`, after tsc. The render worker is each product's own,
// bundled by its own copy of this script: worker.ts here is the library it is
// built on.
//
// The worker is a classic script (an IIFE), which a blob starts in every
// browser, module workers or not. `import.meta.url` is defined away: a blob has
// none, and the one use left in the bundle — the glue's default binary URL —
// never runs, since every candidate names its binary (worker/wasm-loader.ts).
import { build } from "esbuild";
import { rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const dist = join(here, "../dist/worker");

/** `entry`, tsc's output in dist/worker, bundled into one minified script. */
async function bundle(entry) {
    const result = await build({
        entryPoints: [join(dist, entry)],
        bundle: true,
        format: "iife",
        target: "es2022",
        minify: true,
        write: false,
        define: { "import.meta.url": '"about:blank"' },
        logLevel: "warning",
    });
    return result.outputFiles[0].text;
}

/**
 * Rewrite `module` in dist/worker to start `entry`, bundled, from a blob, as
 * its export `starter`.
 */
async function rewrite(module, entry, starter) {
    const bundled = await bundle(entry);
    const source = `// Generated by scripts/bundle-workers.mjs — do not edit. The source this
// replaces, src/worker/local-collaboration-worker-source.ts, says why.
const SOURCE = ${JSON.stringify(bundled)};

// One blob URL for the page's life, however many workers start from it.
let url;

export function ${starter}() {
    url ??= URL.createObjectURL(new Blob([SOURCE], { type: "text/javascript" }));
    return new Worker(url);
}
`;
    writeFileSync(join(dist, module), source);
    // tsc's map is of the source this replaced.
    rmSync(join(dist, `${module}.map`), { force: true });
    console.log(`[bundle-workers] ${entry}: ${Math.round(bundled.length / 1024)} KB -> dist/worker/${module}`);
}

await rewrite("local-collaboration-worker-source.js", "local-collaboration-worker.js", "startLocalCollaborationWorker");
