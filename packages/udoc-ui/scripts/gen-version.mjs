// Write `src/version.ts` from the engine's version.
//
// The engine's version names the `@docmentis/udoc-wasm` the UI falls back to
// on a CDN, so it must be the one the UI's glue was bundled from: this package
// depends on exactly the installed udoc-wasm — the npm release, or a local
// build linked in by scripts/link-engine.mjs — and a build that finds them
// apart fails here, rather than shipping a glue that loads another version's
// binary.
//
// Generated rather than typed out because a hand-kept copy of a version is a
// copy that will be wrong: the release bumps package.json, and nothing would
// have made the constant follow. Committed like the other generated source
// here (`gen:icons`), and re-run by `npm run build` so a bump
// can't ship without it.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const manifest = JSON.parse(readFileSync(join(here, "../package.json"), "utf8"));
// The package's root is the parent of `dist/`, where its entry resolves.
const wasmRoot = join(dirname(fileURLToPath(import.meta.resolve("@docmentis/udoc-wasm"))), "..");
const wasm = JSON.parse(readFileSync(join(wasmRoot, "package.json"), "utf8"));
const out = join(here, "../src/version.ts");

const pin = manifest.dependencies?.[wasm.name];
if (pin !== wasm.version) {
    console.error(
        `[gen-version] ${manifest.name} must depend on exactly ${wasm.name} ${wasm.version} ` +
            `(depends on ${JSON.stringify(pin)})`,
    );
    process.exit(1);
}

const source = `// Generated by scripts/gen-version.mjs — do not edit.
//
// The version of the \`@docmentis/udoc-wasm\` this package is built against,
// whose copy on a CDN it falls back to. Generated from its package.json, which
// is the one place a release bumps.
export const WASM_VERSION = ${JSON.stringify(wasm.version)};
`;

const current = (() => {
    try {
        return readFileSync(out, "utf8");
    } catch {
        return null;
    }
})();

if (current === source) {
    console.log(`[gen-version] src/version.ts already at engine ${wasm.version}`);
} else {
    writeFileSync(out, source);
    console.log(`[gen-version] wrote src/version.ts (engine ${wasm.version})`);
}
