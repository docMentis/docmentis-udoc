// Write `src/version.ts` from this package's version.
//
// The viewer reports its version with every permit request and usage event, so
// the engine's analytics can name the wrapper that produced them. Generated
// rather than typed out because a hand-kept copy of a version is a copy that
// will be wrong: the release bumps package.json, and nothing would have made
// the constant follow.
//
// Committed, and re-run by `npm run build` so a bump can't ship without it.
//
// The viewer is built on `@docmentis/udoc-ui`, and the two release as one: the
// same version, with the viewer depending on exactly the udoc-ui of that
// version. A build that finds them apart fails here, rather than shipping a
// viewer that reports one version and runs another UI.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const manifest = JSON.parse(readFileSync(join(here, "../package.json"), "utf8"));
const ui = JSON.parse(readFileSync(join(here, "../../udoc-ui/package.json"), "utf8"));
const out = join(here, "../src/version.ts");

const pin = manifest.dependencies?.[ui.name];
if (manifest.version !== ui.version || pin !== ui.version) {
    console.error(
        `[gen-version] ${manifest.name} ${manifest.version} must match ${ui.name} ${ui.version} ` +
            `and depend on exactly it (depends on ${JSON.stringify(pin)})`,
    );
    process.exit(1);
}

const source = `// Generated by scripts/gen-version.mjs — do not edit.
//
// This package's version, reported to the engine as the wrapper version so a
// permit request and a usage event can name what produced them. Generated from
// package.json, which is the one place a release bumps.
export const WRAPPER_VERSION = ${JSON.stringify(manifest.version)};
`;

const current = (() => {
    try {
        return readFileSync(out, "utf8");
    } catch {
        return null;
    }
})();

if (current === source) {
    console.log(`[gen-version] src/version.ts already at ${manifest.version}`);
} else {
    writeFileSync(out, source);
    console.log(`[gen-version] wrote src/version.ts (${manifest.version})`);
}
